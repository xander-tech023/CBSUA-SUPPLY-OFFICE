CREATE TABLE IF NOT EXISTS offices (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  office_code VARCHAR(20) NOT NULL,
  name VARCHAR(150) NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_offices_code UNIQUE (office_code),
  CONSTRAINT uq_offices_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS users (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  username VARCHAR(30) NOT NULL,
  password_hash VARCHAR(255) DEFAULT NULL,
  role VARCHAR(8) NOT NULL CHECK (role IN ('admin', 'staff', 'end-user')),
  first_name VARCHAR(80) NOT NULL,
  middle_name VARCHAR(80) DEFAULT NULL,
  surname VARCHAR(80) NOT NULL,
  employee_id VARCHAR(24) DEFAULT NULL,
  position VARCHAR(100) DEFAULT NULL,
  office_id BIGINT DEFAULT NULL,
  email VARCHAR(254) DEFAULT NULL,
  must_change_password SMALLINT NOT NULL DEFAULT 1,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT uq_users_employee_id UNIQUE (employee_id),
  CONSTRAINT uq_users_email UNIQUE (email),
  CONSTRAINT fk_users_office FOREIGN KEY (office_id) REFERENCES offices (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS user_sessions (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id BIGINT NOT NULL,
  token_hash CHAR(64) NOT NULL,
  expires_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_user_sessions_token UNIQUE (token_hash),
  CONSTRAINT fk_user_sessions_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS item_categories (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  category_code VARCHAR(20) NOT NULL,
  name VARCHAR(50) NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_item_categories_code UNIQUE (category_code),
  CONSTRAINT uq_item_categories_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS suppliers (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  supplier_code VARCHAR(30) NOT NULL,
  name VARCHAR(150) NOT NULL,
  category VARCHAR(150) DEFAULT NULL,
  contact_person VARCHAR(150) DEFAULT NULL,
  phone VARCHAR(50) DEFAULT NULL,
  email VARCHAR(254) DEFAULT NULL,
  address TEXT DEFAULT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_suppliers_code UNIQUE (supplier_code),
  CONSTRAINT uq_suppliers_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS inventory_items (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  item_code VARCHAR(30) NOT NULL,
  name VARCHAR(200) NOT NULL,
  description TEXT DEFAULT NULL,
  category_id BIGINT DEFAULT NULL,
  supplier_id BIGINT DEFAULT NULL,
  supply_classification VARCHAR(15) DEFAULT NULL CHECK (supply_classification IN ('Consumable', 'Semi-expendable', 'Fixed Asset')),
  unit VARCHAR(40) NOT NULL,
  quantity_on_hand DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  minimum_quantity DECIMAL(12,2) NOT NULL DEFAULT 0.00,
  expiry_date DATE DEFAULT NULL,
  property_number VARCHAR(80) DEFAULT NULL,
  specifications TEXT DEFAULT NULL,
  estimated_useful_life_years DECIMAL(6,2) DEFAULT NULL,
  unit_cost DECIMAL(14,2) DEFAULT NULL,
  date_acquired DATE DEFAULT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_by BIGINT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_inventory_item_code UNIQUE (item_code),
  CONSTRAINT fk_inventory_category FOREIGN KEY (category_id) REFERENCES item_categories (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_inventory_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_inventory_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS stock_requests (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  request_code VARCHAR(40) NOT NULL,
  request_date DATE NOT NULL,
  office_id BIGINT DEFAULT NULL,
  requester_id BIGINT DEFAULT NULL,
  recipient_name VARCHAR(150) NOT NULL,
  recipient_employee_id VARCHAR(24) DEFAULT NULL,
  item_id BIGINT NOT NULL,
  quantity DECIMAL(12,2) NOT NULL,
  supply_classification VARCHAR(15) NOT NULL CHECK (supply_classification IN ('Consumable', 'Semi-expendable', 'Fixed Asset')),
  document_type VARCHAR(3) NOT NULL CHECK (document_type IN ('RIS', 'ICS', 'PAR')),
  fund_cluster VARCHAR(80) DEFAULT NULL,
  specifications TEXT DEFAULT NULL,
  estimated_useful_life_years DECIMAL(6,2) DEFAULT NULL,
  unit_cost DECIMAL(14,2) DEFAULT NULL,
  supplier_name VARCHAR(150) DEFAULT NULL,
  delivery_receipt_date DATE DEFAULT NULL,
  purchase_order_number VARCHAR(80) DEFAULT NULL,
  purchase_order_date DATE DEFAULT NULL,
  iar_number VARCHAR(80) DEFAULT NULL,
  iar_date DATE DEFAULT NULL,
  property_number VARCHAR(80) DEFAULT NULL,
  date_acquired DATE DEFAULT NULL,
  amount DECIMAL(14,2) DEFAULT NULL,
  status VARCHAR(9) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Issued', 'Cancelled')),
  reviewed_by BIGINT DEFAULT NULL,
  reviewed_at TIMESTAMP DEFAULT NULL,
  cancelled_by BIGINT DEFAULT NULL,
  cancelled_at TIMESTAMP DEFAULT NULL,
  remarks TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_stock_requests_code UNIQUE (request_code),
  CONSTRAINT fk_requests_canceller FOREIGN KEY (cancelled_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_requests_item FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON UPDATE CASCADE,
  CONSTRAINT fk_requests_office FOREIGN KEY (office_id) REFERENCES offices (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_requests_requester FOREIGN KEY (requester_id) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_requests_reviewer FOREIGN KEY (reviewed_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS item_annual_request_budgets (
item_id BIGINT NOT NULL,
  allocation_year SMALLINT NOT NULL,
  annual_limit INTEGER NOT NULL,
  updated_by BIGINT DEFAULT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (item_id, allocation_year),
  CONSTRAINT fk_item_request_budget_item FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_item_request_budget_user FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS office_item_request_quotas (
office_id BIGINT NOT NULL,
  item_id BIGINT NOT NULL,
  allocation_year SMALLINT NOT NULL,
  annual_limit INTEGER NOT NULL,
  updated_by BIGINT DEFAULT NULL,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (office_id, item_id, allocation_year),
