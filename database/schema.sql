  CONSTRAINT fk_office_item_request_quota_user FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS stock_receipts (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  receipt_code VARCHAR(40) NOT NULL,
  item_id BIGINT NOT NULL,
  supplier_id BIGINT DEFAULT NULL,
  quantity DECIMAL(12,2) NOT NULL,
  unit_cost DECIMAL(14,2) DEFAULT NULL,
  received_date DATE NOT NULL,
  received_by BIGINT DEFAULT NULL,
  delivery_reference VARCHAR(100) NOT NULL,
  batch_number VARCHAR(100) DEFAULT NULL,
  expiry_date DATE DEFAULT NULL,
  remarks TEXT DEFAULT NULL,
  attachment_name VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_stock_receipts_code UNIQUE (receipt_code),
  CONSTRAINT uq_stock_receipts_delivery_reference UNIQUE (delivery_reference),
  CONSTRAINT fk_receipts_item FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON UPDATE CASCADE,
  CONSTRAINT fk_receipts_receiver FOREIGN KEY (received_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_receipts_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id) ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS stock_issuances (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  issuance_code VARCHAR(40) NOT NULL,
  request_id BIGINT NOT NULL,
  item_id BIGINT NOT NULL,
  quantity DECIMAL(12,2) NOT NULL,
  issued_date DATE NOT NULL,
  office_id BIGINT DEFAULT NULL,
  recipient_name VARCHAR(150) NOT NULL,
  recipient_employee_id VARCHAR(24) DEFAULT NULL,
  handled_by BIGINT DEFAULT NULL,
  remarks TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT uq_stock_issuances_code UNIQUE (issuance_code),
  CONSTRAINT fk_issuances_handler FOREIGN KEY (handled_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_issuances_item FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON UPDATE CASCADE,
  CONSTRAINT fk_issuances_office FOREIGN KEY (office_id) REFERENCES offices (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_issuances_request FOREIGN KEY (request_id) REFERENCES stock_requests (id) ON UPDATE CASCADE
);

CREATE TABLE IF NOT EXISTS stock_movements (
id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  item_id BIGINT NOT NULL,
  movement_type VARCHAR(10) NOT NULL CHECK (movement_type IN ('Opening', 'Receipt', 'Issuance', 'Adjustment')),
  quantity_change DECIMAL(12,2) NOT NULL,
  quantity_after DECIMAL(12,2) NOT NULL,
  receipt_id BIGINT DEFAULT NULL,
  issuance_id BIGINT DEFAULT NULL,
  performed_by BIGINT DEFAULT NULL,
  notes TEXT DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  CONSTRAINT fk_movements_issuance FOREIGN KEY (issuance_id) REFERENCES stock_issuances (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_movements_item FOREIGN KEY (item_id) REFERENCES inventory_items (id) ON UPDATE CASCADE,
  CONSTRAINT fk_movements_receipt FOREIGN KEY (receipt_id) REFERENCES stock_receipts (id) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT fk_movements_user FOREIGN KEY (performed_by) REFERENCES users (id) ON DELETE SET NULL ON UPDATE CASCADE
);

